/**
 * Filter emojis by category or search query
 */
export const searchEmojis = (query = '', category = null) => {
  const cleanQuery = query.toLowerCase().trim();

  return EMOJI_DATA.filter(item => {
    if (category && category !== 'recent' && item.category !== category) {
      return false;
    }

    if (!cleanQuery) return true;

    return (
      item.emoji.includes(cleanQuery) ||
      item.name.toLowerCase().includes(cleanQuery) ||
      item.keywords.some(k => k.includes(cleanQuery))
    );
  });
};
